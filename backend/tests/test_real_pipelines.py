"""Tests for the real-data pipelines (fake data removed).

Covers the four "real only" channels:
  - potholes: none generated by the simulator (tick never emits a pothole)
  - crashes:  none generated by the simulator (test_crash_detection.py E)
  - ambulance: created ONLY by browser audio siren detection (ambulance_candidate)
  - fatigue:   camera telemetry is authoritative while it flows; the random walk
    runs ONLY as an explicitly-labeled "simulated" fallback when the camera is
    genuinely off.
"""

import os
import sys
import time

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(_HERE))

from app.simulator import SentinelSimulator  # noqa: E402


def test_no_fake_potholes_or_ambulances():
    s = SentinelSimulator()
    types = set()
    for _ in range(200):
        for m in s.tick():
            types.add(m["type"])
            assert m["type"] not in ("pothole", "ambulance", "crash"), (
                f"simulator tick must never fabricate {m['type']}"
            )
    assert "pothole" not in types and "ambulance" not in types and "crash" not in types
    assert s.potholes == [] and s.ambulance is None
    print("A OK: 200 ticks -> no pothole/crash/ambulance events; only fatigue fallback")


def test_siren_creates_real_ambulance():
    s = SentinelSimulator()
    ev = s.ingest({"type": "ambulance_candidate", "freq_hz": 1100, "score": 0.82, "ts": 1755000000000})
    assert ev is not None and ev["type"] == "ambulance", ev
    assert ev["detection_source"] == "audio-siren"
    assert ev["stage"] == "APPROACHING"
    assert ev["siren_freq_hz"] == 1100
    assert ev["siren_score"] == 0.82
    assert ev["distance"] is None
    assert s.ambulance is not None

    # A follow-up report advances to GUIDING.
    ev2 = s.ingest({"type": "ambulance_candidate", "freq_hz": 1180, "score": 0.9, "ts": 1755000000500})
    assert ev2["stage"] == "GUIDING"
    assert ev2["id"] == ev["id"]
    print("B OK: siren ingestion creates APPROACHING -> GUIDING audio-siren ambulance")


def test_siren_clear_and_auto_clear():
    # Explicit clear.
    s = SentinelSimulator()
    s.ingest({"type": "ambulance_candidate", "freq_hz": 900, "score": 0.7})
    clear = s.ingest({"type": "ambulance_clear", "ts": 1755000000000})
    assert clear is not None and clear["stage"] == "CLEARED"
    assert clear["detection_source"] == "audio-siren"
    assert s.ambulance is None

    # Auto-clear safety net after the 6s no-report window.
    s2 = SentinelSimulator()
    s2.ingest({"type": "ambulance_candidate", "freq_hz": 1200, "score": 0.8})
    s2._amb_last_at = time.time() - 10.0
    cleared = [m for m in s2.tick() if m["type"] == "ambulance"]
    assert cleared and cleared[0]["stage"] == "CLEARED"
    assert s2.ambulance is None
    print("C OK: ambulance_clear resolves; stale siren auto-clears after 6s")


def test_camera_fatigue_is_authoritative_no_random_walk():
    s = SentinelSimulator()
    # Simulate the browser reporting real fatigue (source implied "camera").
    s.ingest({"type": "fatigue", "score": 2.0, "perclos": 0.04, "tier": "safe", "ts": int(time.time() * 1000)})
    assert s.fatigue_source == "camera"
    # While camera telemetry flows, the backend relays the camera's own events
    # and never re-broadcasts a tick-generated walk; tick() stays quiet.
    assert s.tick() == [], "no fabricated fatigue while camera is live"
    scores = {2.0}
    for _ in range(10):
        s.ingest({"type": "fatigue", "score": 2.0, "perclos": 0.04, "tier": "safe", "ts": int(time.time() * 1000)})
        s.tick()
        scores.add(s.fatigue["score"])
    assert s.fatigue_source == "camera"
    assert s.fatigue["score"] == 2.0, f"real camera fatigue must pin the score, got {s.fatigue}"
    print("D OK: camera fatigue is authoritative; random walk never runs while camera is live")


def test_camera_off_labels_simulated_fallback():
    s = SentinelSimulator()
    s.ingest({"type": "fatigue", "score": 3.0, "perclos": 0.06, "tier": "safe", "ts": int(time.time() * 1000)})
    assert s.fatigue_source == "camera"
    # Let the client TTL expire -> the walk resumes but labeled simulated.
    s._client_fatigue_at = 0.0
    fallback = [m for m in s.tick() if m["type"] == "fatigue"]
    assert fallback and fallback[0]["source"] == "simulated"
    assert fallback[0]["face"] is False
    assert fallback[0]["nod"] is None
    assert s.fatigue_source == "simulated"
    print("E OK: camera-off -> labeled SIMULATED fallback (face=False, nod=None)")


def test_fatigue_relays_real_nod_face():
    s = SentinelSimulator()
    ev = s.ingest({
        "type": "fatigue",
        "score": 7.4,
        "perclos": 0.22,
        "tier": "moderate",
        "face": True,
        "nod": {"pitchDeg": 14.2, "droopRatio": 0.045, "droopActive": True, "droopSustainedMs": 2500},
        "ts": 1755000000000,
    })
    assert ev["source"] == "camera"
    assert ev["face"] is True
    assert ev["nod"] == {"pitchDeg": 14.2, "droopRatio": 0.045, "droopActive": True, "droopSustainedMs": 2500}
    print("F OK: camera fatigue relays the browser's real nod/face evidence verbatim")


if __name__ == "__main__":
    test_no_fake_potholes_or_ambulances()
    test_siren_creates_real_ambulance()
    test_siren_clear_and_auto_clear()
    test_camera_fatigue_is_authoritative_no_random_walk()
    test_camera_off_labels_simulated_fallback()
    test_fatigue_relays_real_nod_face()
    print("\nALL REAL-PIPELINE TESTS PASS")